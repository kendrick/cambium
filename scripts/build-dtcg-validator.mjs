import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Ajv compiles a schema with `new Function`, which a static site can only run by adding
// `'unsafe-eval'` to its CSP `script-src`. Precompiling here moves the compile to build time and
// keeps the CSP clean. It is also the smaller half of the trade: 13.0 kB for the standalone
// validator against 40.9 kB for Ajv plus the schema at runtime.
//
// Run this whenever the vendored schema changes, and commit the output. `core/dtcg/validator.test.ts`
// regenerates and diffs, so a stale generated file fails the suite rather than shipping.

const SCHEMA = new URL('../core/dtcg/format.2025.10.json', import.meta.url);

// The committed path is the default. `core/dtcg/validator.test.ts` passes a scratch path so it can
// regenerate and diff without touching the file it is checking.
// `pathToFileURL`, not string concatenation: a working directory containing a space or a `#`
// does not survive being pasted into a URL.
const TARGET = process.argv[2]
	? pathToFileURL(resolve(process.argv[2]))
	: new URL('../core/dtcg/format-validator.generated.mjs', import.meta.url);

const schema = JSON.parse(await readFile(SCHEMA, 'utf8'));

// Ajv's plain entry point, never `ajv/dist/2020`: the schema declares draft-07.
//
// `allErrors` is on because a token file with twenty bad tokens should report twenty, and because
// on this schema it is also the smaller build: collecting errors generates one code path where
// failing fast generates an early return per branch. Measured at 24.9 kB gzipped against 25.9 kB
// with `allErrors` off.
const ajv = new Ajv({ code: { source: true, esm: true }, allErrors: true, strict: true });

// The schema uses `uri-reference` and `json-pointer-uri-fragment`. Without ajv-formats, strict
// mode throws `unknown format` before it compiles anything.
addFormats(ajv);

const source = standaloneCode(ajv, ajv.compile(schema));

const banner = `// Generated by scripts/build-dtcg-validator.mjs from core/dtcg/format.2025.10.json.
// Do not edit. Run \`pnpm dtcg:build\` instead.
`;

await writeFile(TARGET, `${banner}${source}`);

// Ajv's standalone output carries no types, and `core/dtcg/validate.ts` has to import it. Emitting
// the declaration here rather than hand-writing one keeps the pair in step: regenerate both, diff
// both. The shape is fixed by Ajv's single-schema output, which exports one validator function
// hanging its last failure off `.errors`.
const types = `${banner}
export type DtcgSchemaError = {
	instancePath: string;
	schemaPath: string;
	keyword: string;
	message?: string;
	params: Record<string, unknown>;
};

export type DtcgSchemaValidator = ((data: unknown) => boolean) & {
	errors?: DtcgSchemaError[] | null;
};

export declare const validate: DtcgSchemaValidator;
export default validate;
`;

await writeFile(new URL(`${TARGET.href.replace(/\.mjs$/, '')}.d.mts`), types);

console.log(`${fileURLToPath(TARGET)}
  ${Buffer.byteLength(banner) + Buffer.byteLength(source)} bytes`);
